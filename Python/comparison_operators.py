# comparison Operators

# | Operator | Meaning                  |
# | -------- | ------------------------ |
# | `==`     | Equal to                 |
# | `!=`     | Not equal to             |
# | `<`      | Less than                |
# | `>`      | Greater than             |
# | `<=`     | Less than or equal to    |
# | `>=`     | Greater than or equal to |

# Equal to
# Checks whether two values are equal.
a = 6
b = 6
print(a == b)

# Not Equal to
# Checks whether two values are different.
a = 6
b = 5
print(a != b)

# Greater Than
a = 10
b = 5
print(a > b)

#  Less Than
a = 5
b = 10
print(a < b)

#  Greater Than or Equal To
a = 10
b = 10
print(a >= b)

#  Less Than or Equal To
a = 5
b = 10
print(a <= b)
