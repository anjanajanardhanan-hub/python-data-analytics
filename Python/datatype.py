# datatypes
# integer
# float
# boolean
# string

# | Data Type | Meaning        | Example   |
# | --------- | -------------- | --------- |
# | `int`     | Whole number   | `10`      |
# | `float`   | Decimal number | `10.5`    |
# | `str`     | Text           | `"Hello"` |
# | `bool`    | True/False     | `True`    |


# integer
a = 5
print(a)

# float
a = 5.5
print(a)

# boolean
a = 10
print(a > 5)
a = 10
print(a < 5)

# string
name = "Alan"
print(name)

# string concatenation
print("5" + "5")

# | Escape sequence | Meaning      |
# | --------------- | ------------ |
# | `\'`            | Single quote |
# | `\"`            | Double quote |
# | `\n`            | New line     |

a = 'mohan\'s resume'
print(a)
# newline\n
qt = "gandhi once said that\n\"say no to violence\""
print(qt)


# Type casting
# means converting a value from one data type to another data type.

# For example, converting a string into an integer.

# int()    → converts to integer
# float()  → converts to float
# str()    → converts to string
# bool()   → converts to Boolean

#  Converting String to int
a = "5"
b = 5
print(int(a) + b)

